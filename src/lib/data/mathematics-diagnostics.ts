export function getMathematicsDiagnostic(courseSlug: string): CourseDiagnostic | undefined {
  if (MATHEMATICS_DIAGNOSTICS[courseSlug]) {
    return MATHEMATICS_DIAGNOSTICS[courseSlug];
  }

  // Fallbacks based on closest level for mathematics
  if (courseSlug.includes("jamb")) {
    return MATHEMATICS_DIAGNOSTICS["jamb-utme-speed-mathematics"];
  }
  if (courseSlug.includes("pri") || courseSlug.includes("common-entrance")) {
    return MATHEMATICS_DIAGNOSTICS["primary6-quantitative-reasoning-common-entrance"];
  }
  if (courseSlug.includes("jss") || courseSlug.includes("bece")) {
    return MATHEMATICS_DIAGNOSTICS["jss3-basic-mathematics-bece-prep"];
  }
  if (courseSlug.includes("algebra") || courseSlug.includes("ss2")) {
    return MATHEMATICS_DIAGNOSTICS["ss2-algebra-and-trigonometry-deep-dive"];
  }
  if (courseSlug.includes("igcse")) {
    return MATHEMATICS_DIAGNOSTICS["cambridge-igcse-extended-mathematics"];
  }

  return MATHEMATICS_DIAGNOSTICS["waec-ssce-mathematics-mastery"];
}
