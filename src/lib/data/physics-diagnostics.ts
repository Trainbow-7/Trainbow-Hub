export function getPhysicsDiagnostic(courseSlug: string): CourseDiagnostic | undefined {
  if (PHYSICS_DIAGNOSTICS[courseSlug]) {
    return PHYSICS_DIAGNOSTICS[courseSlug];
  }

  // Smart fallback mapping by level or topic for other courses
  if (courseSlug.includes("ss1") || courseSlug.includes("measurement") || courseSlug.includes("mechanics")) {
    return PHYSICS_DIAGNOSTICS["physics-ss1-measurement-motion-forces"];
  }
  if (courseSlug.includes("ss2") || courseSlug.includes("heat") || courseSlug.includes("waves") || courseSlug.includes("optics")) {
    return PHYSICS_DIAGNOSTICS["physics-ss2-energy-heat-waves-light"];
  }
  return PHYSICS_DIAGNOSTICS["physics-ss3-electricity-magnetism-modern"];
}

